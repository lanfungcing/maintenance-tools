#!/usr/bin/env python3
"""
对指定的 formula 生成 "rebuild" PR：删除 formula 中的 bottle do ... end 块及其后一行，
让 CI 重新构建并上传缺失的 bottle。

用法:
  python3 create-rebuild-pr.py <formula> [<formula> ...]
  python3 create-rebuild-pr.py --file bottle_missing.json
  python3 create-rebuild-pr.py --dry-run <formula>

前置:
  - 环境变量 ATOMGIT_USER / ATOMGIT_EMAIL / ATOMGIT_TOKEN
  - 本地已 tap harmonybrew/core（brew --repository harmonybrew/core）

每个 formula 会:
  1. 定位 Formula/<首字母>/<name>.rb 文件
  2. 删除 bottle do ... end 块及其后一行空行
  3. 基于 main 创建分支 rebuild-<name>，提交（作者 HarmonybrewBot），push -f 到个人 fork
  4. 创建标题为 "<name>: rebuild" 的 PR（base=main）
"""

import argparse
import os
import subprocess
import sys

import requests

# 环境变量
ATOMGIT_USER = os.getenv("ATOMGIT_USER")
ATOMGIT_EMAIL = os.getenv("ATOMGIT_EMAIL")
ATOMGIT_TOKEN = os.getenv("ATOMGIT_TOKEN")

BOT_AUTHOR = "HarmonybrewBot <HarmonybrewBot@noreply.gitcode.com>"
OWNER = "Harmonybrew"
REPO = "homebrew-core"
BASE_BRANCH = "main"
PUSH_REPO = f"https://{ATOMGIT_USER}:{ATOMGIT_TOKEN}@atomgit.com/{ATOMGIT_USER}/{REPO}.git"


def check_env():
    """校验必需环境变量。"""
    for var in ["ATOMGIT_USER", "ATOMGIT_EMAIL", "ATOMGIT_TOKEN"]:
        if not os.getenv(var):
            sys.exit(f"Error: Environment variable {var} is missing.")


def run_cmd(cmd, cwd=None):
    """运行 Shell 命令并返回 stdout，失败则退出。"""
    # 打印命令时对含 token 的参数脱敏，避免 token 泄露到日志
    display = " ".join(
        "***" if (ATOMGIT_TOKEN and ATOMGIT_TOKEN in part) else part for part in cmd
    )
    print(f"[*] Running: {display}")
    result = subprocess.run(cmd, cwd=cwd, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    print(result.stdout)
    if result.returncode != 0:
        print(f"[!] Command failed with exit code {result.returncode}")
        sys.exit(result.returncode)
    return result.stdout.strip()


def formula_path(formula):
    """返回 formula 文件在 tap 中的相对路径。lib* 归入 Formula/lib/。"""
    first_letter = "lib" if formula.startswith("lib") else formula[0].lower()
    return f"Formula/{first_letter}/{formula}.rb"


def remove_bottle_block(text):
    """删除 bottle do ... end 块及其后一行空行。返回 (新文本, 是否删除)。"""
    lines = text.splitlines(keepends=True)
    n = len(lines)
    for start in range(n):
        if lines[start].strip() != "bottle do":
            continue
        indent = lines[start][: len(lines[start]) - len(lines[start].lstrip())]
        # 找同缩进的 end 行
        end = None
        for j in range(start + 1, n):
            cur = lines[j]
            cur_indent = cur[: len(cur) - len(cur.lstrip())]
            if cur_indent == indent and cur.strip() == "end":
                end = j
                break
        if end is None:
            continue
        # 若 end 后紧跟一行空行，一并删除
        delete_end = end
        if end + 1 < n and lines[end + 1].strip() == "":
            delete_end = end + 1
        del lines[start : delete_end + 1]
        return "".join(lines), True
    return text, False


def check_pr_exists(title):
    """检查 Harmonybrew/homebrew-core 是否已存在同标题的 open PR。"""
    url = f"https://api.atomgit.com/api/v5/repos/{OWNER}/{REPO}/pulls"
    page = 1
    while True:
        params = {
            "access_token": ATOMGIT_TOKEN,
            "state": "open",
            "base": BASE_BRANCH,
            "per_page": 100,
            "page": page,
        }
        try:
            resp = requests.get(url, params=params, timeout=15)
            resp.raise_for_status()
            prs = resp.json()
        except requests.exceptions.RequestException as exc:
            print(f"[ERROR] Failed to check PR: {exc}")
            sys.exit(1)

        if any(pr.get("title") == title for pr in prs):
            return True
        if len(prs) < 100:
            return False
        page += 1


def create_pr(head_branch, title):
    """通过 AtomGit API 创建 PR。"""
    url = f"https://api.atomgit.com/api/v5/repos/{OWNER}/{REPO}/pulls"
    params = {"access_token": ATOMGIT_TOKEN}
    payload = {
        "title": title,
        "head": head_branch,  # 格式 "username:branch"
        "base": BASE_BRANCH,
        "body": (
            "Removes the `bottle` block so CI will rebuild and re-upload the bottle. "
            "Automatically generated by [maintenance-tools]"
            "(https://github.com/lanfungcing/maintenance-tools)."
        ),
        "prune_source_branch": True,  # 合入后删除源分支
    }
    try:
        resp = requests.post(url, params=params, json=payload, timeout=30)
        resp.raise_for_status()
        print(f"[SUCCESS] PR created: https://atomgit.com/{OWNER}/{REPO}/pull/{resp.json().get('number')}")
    except requests.exceptions.RequestException as exc:
        print(f"[ERROR] Failed to create PR: {exc}")
        if resp is not None:
            print(f"Response: {resp.text}")
        sys.exit(1)


def parse_args():
    parser = argparse.ArgumentParser(description="对 formula 生成 rebuild PR（删除 bottle 块）")
    parser.add_argument("formulas", nargs="*", help="一个或多个 formula 名")
    parser.add_argument("--file", help="从 JSON 数组文件读取 formula 名列表")
    parser.add_argument("--dry-run", action="store_true", help="只删除 bottle 块并打印，不提交/推送/创建 PR")
    return parser.parse_args()


